export function detectLanguage() {
  try {
    const saved = localStorage.getItem("uy_admin_lang");
    if (saved && translations[saved]) {
      return saved;
    }
  } catch {
    // localStorage может быть недоступен
  }

  const code = (navigator.language || "ru").toLowerCase();

  if (code.includes("cyrl")) {
    return "uzc";
  }

  if (code.startsWith("uz")) {
    return "uz";
  }

  return "ru";
}
